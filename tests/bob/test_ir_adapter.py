def test_display_macros_with_names_the_ir_rejects():
    """A ``<macros>`` name the IR rejects never fails the conversion.

    Unreferenced, it is dropped with a root warning; referenced, its default follows the rename.
    """
    data = (
        b'<display version="2.0.0"><name>M</name><macros><A-B>x</A-B><_6X>7</_6X><P>SR:</P></macros>'
        b'<widget type="textupdate" version="2.0.0"><name>T</name><pv_name>${P}${_6X}</pv_name></widget>'
        b"</display>"
    )
    wire = to_wire_dict(convert_bytes(data, kind="bob"))
    assert validate_screen_json(wire) == []
    assert {m["name"]: m["default"] for m in wire["macros"]} == {"P": "SR:", "M__6X": "7"}
    assert any("A-B" in w for w in wire["root"].get("warnings", []))


