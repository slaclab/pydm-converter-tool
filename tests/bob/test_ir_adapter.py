"""Golden and behaviour tests for the Phoebus ``.bob`` -> Screen IR orchestrator.

Every ``tests/bob/fixtures/*.bob`` is a synthetic, one-construct display. Its golden
``<name>.screen.json`` is the committed output of :func:`bob_file_to_ir`; each golden
test asserts byte-identical output across two runs, equality with the golden and a clean
``validate_screen_json``. The focused tests below pin the PROPOSAL acceptance points so a
golden regenerated by mistake cannot silently change them.

Regenerate the goldens after an intended output change with::

    ~/.venv/bin/python -c "from tests.bob.test_ir_adapter import regenerate; regenerate()"
"""

from __future__ import annotations

from pathlib import Path

import pytest

from pydmconverter.bob.ir_adapter import bob_file_to_ir
from pydmconverter.bob.parser import BobParseError
from pydmconverter.ir.emit import to_json, to_wire_dict
from pydmconverter.ir.schema import validate_screen_json
from pydmconverter.react import convert_bytes

FIXTURES = Path(__file__).parent / "fixtures"
COLOR_DEF = FIXTURES / "color.def"
FIXTURE_NAMES = sorted(p.stem for p in FIXTURES.glob("*.bob"))


def _convert(name: str):
    color_def = COLOR_DEF if name == "color_def" else None
    return bob_file_to_ir(FIXTURES / f"{name}.bob", color_def_path=color_def)


def _wire(name: str) -> dict:
    return to_wire_dict(_convert(name))


def _children(name: str) -> list[dict]:
    return _wire(name)["root"]["children"]


def regenerate() -> None:
    """Rewrite every golden from the current adapter output (LF line endings)."""
    for name in FIXTURE_NAMES:
        golden = FIXTURES / f"{name}.screen.json"
        golden.write_text(to_json(_convert(name)), encoding="utf-8", newline="")


