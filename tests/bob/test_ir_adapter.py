def test_transparent_buttons_carry_transparent_prop():
    clear, solid, clear_bool = _children("action_button_transparent")
    assert clear["type"] == "regular-button"
    assert clear["props"]["transparent"] is True
    assert clear["props"]["label"] == "Go"
    assert clear.get("warnings", []) == []
    assert "transparent" not in solid["props"]
    assert clear_bool["type"] == "pv-button"
    assert clear_bool["props"]["transparent"] is True
    assert clear_bool["props"]["pv"] == "SR:B0"


def test_bool_button_images_led_by_a_macro_are_dropped():
    """A macro before the first ``/`` could expand to a scheme: the image is not a file path."""
    clear_bool = _children("action_button_transparent")[2]
    assert "onImage" not in clear_bool["props"] and "offImage" not in clear_bool["props"]
    assert clear_bool["warnings"] == [
        "ClearBool: on_image '$(IMG)/on.png' is not a file path; dropped",
        "ClearBool: off_image '${IMG}/off.png' is not a file path; dropped",
    ]


def test_embedded_file_led_by_a_macro_is_dropped():
    embedded = _wire("macros")["root"]["children"][1]
    assert "file" not in embedded["props"]
    assert embedded["warnings"] == ["Child: file '$(EPSFile)' is not a file path; dropped"]


def _one_widget(body: str) -> dict:
    data = f'<display version="2.0.0"><name>D</name>{body}</display>'.encode()
    return to_wire_dict(convert_bytes(data, kind="bob"))["root"]["children"][0]


@pytest.mark.parametrize(
    "ref", ["javascript:alert(1)", "https://evil.example/x.png", "file:///etc/passwd", "${X}/a.png"]
)
@pytest.mark.parametrize(
    ("widget", "prop"),
    [("picture", "file"), ("embedded", "file"), ("bool_button", "on_image"), ("bool_button", "off_image")],
)
def test_file_props_that_are_not_paths_are_dropped(widget, prop, ref):
    node = _one_widget(f'<widget type="{widget}" version="2.0.0"><name>W</name><{prop}>{ref}</{prop}></widget>')
    assert ref not in str(node["props"])
    assert f"W: {prop} {ref!r} is not a file path; dropped" in node["warnings"]


@pytest.mark.parametrize("ref", ["pics/a.png", "/opt/ops/a.png", "../shared/${DEV}.png"])
def test_picture_file_paths_pass(ref):
    node = _one_widget(f'<widget type="picture" version="2.0.0"><name>W</name><file>{ref}</file></widget>')
    assert node.get("warnings", []) == []
    assert ref.replace("$(", "${") in str(node["props"])


def test_open_display_that_is_not_a_path_is_dropped():
    node = _one_widget(
        '<widget type="action_button" version="3.0.0"><name>B</name><actions>'
        '<action type="open_display"><file>javascript:alert(1)</file></action>'
        '<action type="open_display"><file>ok.bob</file></action>'
        "</actions></widget>"
    )
    assert [a["file"] for a in node["props"]["actions"]] == ["ok.screen.json"]
    assert "B: open_display 'javascript:alert(1)' is not a file path; dropped" in node["warnings"]


@pytest.mark.parametrize("value", ["javascript:alert(1)", "${F}"])
def test_file_rule_with_a_value_that_is_not_a_path_is_dropped(value):
    node = _one_widget(
        '<widget type="picture" version="2.0.0"><name>W</name><file>a.png</file>'
        '<rules><rule name="img" prop_id="file" out_exp="false">'
        f'<exp bool_exp="pv0 == 1"><value>{value}</value></exp><pv_name>loc://x</pv_name>'
        "</rule></rules></widget>"
    )
    assert node.get("rules", []) == []
    assert f"W: rule 'img' value {value!r} is not a file path; dropped" in node["warnings"]
