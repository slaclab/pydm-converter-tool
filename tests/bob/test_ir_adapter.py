def test_golden(name):
    first = to_json(_convert(name))
    second = to_json(_convert(name))
    assert first == second, "conversion is not byte-stable across runs"
    golden = FIXTURES / f"{name}.screen.json"
    assert golden.is_file(), f"missing golden {golden.name}; run regenerate()"
    assert first == golden.read_text(encoding="utf-8")


